/**
 * Builds the token outputs from the DTCG sources in `tokens/`.
 *
 *   tokens/primitive  ─┐
 *   tokens/semantic   ─┼─ Style Dictionary (parse, resolve, transform) ─┬─ tokens.css  runtime CSS vars, light + dark
 *   tokens/component  ─┘     once per mode: light, dark                  ├─ theme.css   Tailwind v4 @theme (semantic + component only)
 *                                                                        └─ tokens.ts   typed metadata (for code and the MCP server)
 *
 * Run: `pnpm --filter @tessera/tokens tokens` (writes src/generated/).
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import StyleDictionary from "style-dictionary";
import type { TransformedToken } from "style-dictionary/types";

export type Mode = "light" | "dark";
export type Tier = "primitive" | "semantic" | "component";

/** One public (semantic or component) token, with its value in each mode. */
export interface TokenEntry {
  /** Kebab-case name, e.g. `color-fg-muted`. */
  name: string;
  tier: "semantic" | "component";
  /** DTCG `$type`, e.g. `color`, `dimension`, `shadow`. */
  type: string;
  /** Runtime CSS custom property, e.g. `--tsr-color-fg-muted`. */
  cssVar: string;
  /** Tailwind theme variable, e.g. `--color-fg-muted` (gives `text-fg-muted`, `bg-fg-muted`). */
  themeVar: string;
  light: string;
  dark: string;
  description: string;
}

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
export const tokensDir: string = join(packageRoot, "tokens");
export const generatedDir: string = join(packageRoot, "src", "generated");

const PREFIX = "tsr";
const HEADER =
  "Generated by @tessera/tokens from tokens/*.json. Do not edit by hand: run `pnpm --filter @tessera/tokens tokens`.";

// ---------------------------------------------------------------------------
// Style Dictionary setup
// ---------------------------------------------------------------------------

interface DtcgColor {
  colorSpace: string;
  components: number[];
  alpha?: number;
}

function isDtcgColor(value: unknown): value is DtcgColor {
  return (
    typeof value === "object" && value !== null && "colorSpace" in value && "components" in value
  );
}

const round = (n: number): number => Math.round(n * 10_000) / 10_000;

/** DTCG color object → CSS `oklch(L C H / a)`. SD's built-in `color/css` would convert to hex. */
export function colorToCss(value: unknown): string {
  if (typeof value === "string") return value;
  if (!isDtcgColor(value) || value.colorSpace !== "oklch") {
    throw new Error(
      `Unsupported color value ${JSON.stringify(value)}: use {"colorSpace": "oklch", ...}`,
    );
  }
  const [l, c, h] = value.components.map(round);
  const alpha = value.alpha === undefined || value.alpha === 1 ? "" : ` / ${round(value.alpha)}`;
  return `oklch(${l} ${c} ${h}${alpha})`;
}

StyleDictionary.registerTransform({
  name: "tessera/color/oklch",
  type: "value",
  transitive: true,
  filter: (token) => token.$type === "color",
  transform: (token) => colorToCss(token.$value),
});

const builtInCss: string[] = StyleDictionary.hooks.transformGroups.css ?? [];
const transforms: string[] = [
  ...builtInCss.filter((name) => name !== "color/css" && name !== "name/kebab"),
  "tessera/color/oklch",
  "name/kebab",
];

/** The tier is the first folder under tokens/. Primitives must also sit under the `primitive.` root. */
function tierOf(token: TransformedToken): Tier {
  const tier = relative(tokensDir, token.filePath).split(sep)[0];
  if (tier !== "primitive" && tier !== "semantic" && tier !== "component") {
    throw new Error(
      `${token.filePath}: token files must live in tokens/{primitive,semantic,component}/`,
    );
  }
  if ((tier === "primitive") !== (token.path[0] === "primitive")) {
    throw new Error(
      `${token.name}: primitives, and only primitives, go under the "primitive" root group`,
    );
  }
  return tier;
}

/** Resolves every token for one mode. Throws on broken references and token collisions. */
export async function resolveTokens(mode: Mode): Promise<TransformedToken[]> {
  const sd = new StyleDictionary({
    source: [
      `${tokensDir}/primitive/**/*.json`,
      `${tokensDir}/semantic/*.json`,
      `${tokensDir}/semantic/${mode}/**/*.json`,
      `${tokensDir}/component/**/*.json`,
    ],
    usesDtcg: true,
    // Verbose: a broken reference names the token and the missing path.
    log: { warnings: "error", verbosity: "verbose" },
    platforms: { tessera: { transforms } },
  });
  const { allTokens } = await sd.getPlatformTokens("tessera");
  return allTokens;
}

// ---------------------------------------------------------------------------
// Model
// ---------------------------------------------------------------------------

/** Maps a token path to its Tailwind v4 theme variable. Unknown groups fail the build on purpose. */
export function themeVarOf(path: string[]): string {
  const [group, ...rest] = path;
  const key = rest.join("-");
  switch (group) {
    case "color":
    case "spacing":
    case "radius":
    case "font":
    case "font-weight":
    case "shadow":
      return `--${group}-${key}`;
    case "text": {
      // text.sm.size → --text-sm, text.sm.line-height → --text-sm--line-height
      const [size, prop] = rest;
      if (prop === "size") return `--text-${size}`;
      if (prop === "line-height") return `--text-${size}--line-height`;
      throw new Error(
        `text.${rest.join(".")}: expected text.<size>.size or text.<size>.line-height`,
      );
    }
    default:
      throw new Error(
        `No Tailwind namespace for token group "${group}". Add it to themeVarOf() and THEME_RESETS in scripts/build-tokens.ts.`,
      );
  }
}

/** Tailwind namespaces we own. Their defaults are removed so only Tessera tokens exist. */
export const THEME_RESETS: readonly string[] = [
  "--color-*",
  "--spacing",
  "--spacing-*",
  "--radius-*",
  "--font-*",
  "--font-weight-*",
  "--text-*",
  "--leading-*",
  "--tracking-*",
  "--shadow-*",
  "--inset-shadow-*",
  "--drop-shadow-*",
  "--text-shadow-*",
];

const valueToCss = (value: unknown): string => (typeof value === "string" ? value : String(value));

export async function buildModel(): Promise<{ entries: TokenEntry[]; primitiveNames: string[] }> {
  const [light, dark] = await Promise.all([resolveTokens("light"), resolveTokens("dark")]);
  const darkByName = new Map(dark.map((token) => [token.name, token]));

  const primitiveNames: string[] = [];
  const entries: TokenEntry[] = [];
  for (const token of light) {
    const tier = tierOf(token);
    if (tier === "primitive") {
      primitiveNames.push(token.name);
      continue;
    }
    const darkToken = darkByName.get(token.name);
    if (!darkToken) throw new Error(`${token.name} has no dark value`);
    entries.push({
      name: token.name,
      tier,
      type: String(token.$type),
      cssVar: `--${PREFIX}-${token.name}`,
      themeVar: themeVarOf(token.path),
      light: valueToCss(token.$value),
      dark: valueToCss(darkToken.$value),
      description: token.$description ?? "",
    });
  }
  return { entries, primitiveNames };
}

// ---------------------------------------------------------------------------
// Formats
// ---------------------------------------------------------------------------

export function formatTokensCss(entries: TokenEntry[]): string {
  const changesInDark = entries.filter((entry) => entry.dark !== entry.light);
  return [
    `/* ${HEADER} */`,
    "",
    ":root {",
    "  color-scheme: light;",
    ...entries.map((entry) => `  ${entry.cssVar}: ${entry.light};`),
    "}",
    "",
    '[data-theme="dark"] {',
    "  color-scheme: dark;",
    ...changesInDark.map((entry) => `  ${entry.cssVar}: ${entry.dark};`),
    "}",
    "",
  ].join("\n");
}

export function formatThemeCss(entries: TokenEntry[]): string {
  return [
    `/* ${HEADER} */`,
    "/* Tailwind v4 theme: semantic and component tokens only. Primitives are never exposed. */",
    "",
    '@import "./tokens.css";',
    "",
    "/* Remove Tailwind's default palette and scales in every namespace Tessera owns. */",
    "@theme {",
    ...THEME_RESETS.map((name) => `  ${name}: initial;`),
    "}",
    "",
    "/* inline: utilities read the runtime var directly, so [data-theme] switches them. */",
    "@theme inline {",
    ...entries.map((entry) => `  ${entry.themeVar}: var(${entry.cssVar});`),
    "}",
    "",
  ].join("\n");
}

export function formatTokensTs(entries: TokenEntry[]): string {
  const body = Object.fromEntries(entries.map(({ name, ...rest }) => [name, rest]));
  return [
    `// ${HEADER}`,
    "",
    "/** Every public Tessera token (semantic and component tiers), with light and dark values. */",
    `export const tokens = ${JSON.stringify(body, null, 2)} as const;`,
    "",
    "/** A public token name, e.g. `color-fg-muted` or `spacing-md`. */",
    "export type TokenName = keyof typeof tokens;",
    "",
  ].join("\n");
}

/** Builds all outputs into `outDir`. Returns the written file paths. */
export async function buildTokens(outDir: string = generatedDir): Promise<string[]> {
  const { entries } = await buildModel();
  await mkdir(outDir, { recursive: true });
  const files: [string, string][] = [
    ["tokens.css", formatTokensCss(entries)],
    ["theme.css", formatThemeCss(entries)],
    ["tokens.ts", formatTokensTs(entries)],
  ];
  await Promise.all(files.map(([file, content]) => writeFile(join(outDir, file), content)));
  return files.map(([file]) => join(outDir, file));
}

if (import.meta.main) {
  const written = await buildTokens();
  for (const file of written) console.log(`wrote ${file}`);
}
